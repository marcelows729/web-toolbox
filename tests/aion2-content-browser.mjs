import assert from 'node:assert/strict'
import {navigate,evaluate,input,click,viewport,assertNoOverflow,screenshot,wait} from './browser-client.mjs'
const key='poketsuru-aion2-content-v1'
const stored=()=>evaluate(`JSON.parse(localStorage.getItem('${key}'))`)
export async function checkAion2Content() {
  await navigate('/'); await evaluate(`localStorage.removeItem('${key}')`); await navigate('/tools/aion2-checklist'); await wait(100)
  assert.equal(await evaluate(`document.querySelector('[data-content-id="nightmare"] input').value`),'')
  await input('[data-content-id="nightmare"] input','6')
  assert.equal(Object.values((await stored()).entries)[0].value,6)
  await click('[data-content-id="nightmare"] .text-button')
  assert.equal(await evaluate(`!!document.querySelector('[data-content-id="nightmare"]')`),false)
  await navigate('/tools/aion2-checklist')
  assert.equal(await evaluate(`!!document.querySelector('[data-content-id="nightmare"]')`),false)
  await click('.aion2-content-hidden summary'); await click('.aion2-content-hidden button')
  assert.equal(await evaluate(`document.querySelector('[data-content-id="nightmare"] input').value`),'6')
  await click('.aion2-content-config summary'); await input('[aria-label="キャラクター識別名"]','sub')
  assert.equal(await evaluate(`document.querySelector('[data-content-id="nightmare"] input').value`),'')
  await input('[data-content-id="duty"] input','3')
  await input('[aria-label="キャラクター識別名"]','main')
  assert.equal(await evaluate(`document.querySelector('[data-content-id="duty"] input').value`),'3')
  assert.equal(await evaluate(`document.querySelector('[data-content-id="nightmare"] input').value`),'6')
  await input('.aion2-content > .field-label input','悪夢')
  await navigate('/tools/aion2-checklist')
  assert.equal(await evaluate(`document.querySelectorAll('.aion2-content-card').length`),1)
  assert.equal((await stored()).view.search,'悪夢')
  await input('.aion2-content > .field-label input','')
  for(const theme of ['light','dark'])for(const width of [320,375,768,1280]) {
    await viewport(width); await click(theme==='light'?'.theme-option:first-child':'.theme-option:last-child'); await assertNoOverflow()
    await evaluate(`document.querySelector('[data-content-id="nightmare"]').scrollIntoView({block:'center',behavior:'instant'})`)
    await screenshot((process.env.TEMP||'.').replaceAll('\\','/')+`/aion2-content-${theme}-${width}.png`)
    assert.ok(await evaluate(`document.querySelector('[data-content-id="nightmare"] button').getBoundingClientRect().height>=44`))
  }
  const backup=JSON.stringify(await stored())
  await evaluate(`(()=>{const dt=new DataTransfer();dt.items.add(new File([${JSON.stringify(backup)}],'backup.json',{type:'application/json'}));const el=document.querySelector('.aion2-content input[type=file]');el.files=dt.files;el.dispatchEvent(new Event('change',{bubbles:true}));})()`); await wait(200)
  assert.ok(await evaluate(`!!document.querySelector('.aion2-content .aion2-restore-preview')`))
  await click('.aion2-content .aion2-restore-preview .secondary-button')
  assert.equal(JSON.stringify(await stored()),backup)
  await input('[data-content-id="nightmare"] input','4')
  await evaluate(`(()=>{const dt=new DataTransfer();dt.items.add(new File([${JSON.stringify(backup)}],'backup.json',{type:'application/json'}));const el=document.querySelector('.aion2-content input[type=file]');el.files=dt.files;el.dispatchEvent(new Event('change',{bubbles:true}));})()`); await wait(200)
  await click('.aion2-content .aion2-restore-preview .primary-button')
  assert.equal(JSON.stringify(await stored()),backup)
  await evaluate(`window.contentNativeSet=Storage.prototype.setItem;Storage.prototype.setItem=function(k,v){if(k==='${key}')throw new DOMException('quota','QuotaExceededError');return window.contentNativeSet.call(this,k,v)}`)
  await input('[data-content-id="nightmare"] input','5')
  assert.equal(JSON.stringify(await stored()),backup)
  assert.equal(await evaluate(`document.querySelector('[data-content-id="nightmare"] input').value`),'5')
  await navigate('/tools/aion2-checklist')
  assert.equal(await evaluate(`document.querySelector('[data-content-id="nightmare"] input').value`),'6')
  const changed=await stored(); changed.view.search='別タブの検索'
  await evaluate(`localStorage.setItem('${key}',${JSON.stringify(JSON.stringify(changed))})`)
  await input('[data-content-id="nightmare"] input','4')
  assert.deepEqual(await stored(),changed)
  assert.ok(await evaluate(`document.querySelector('.aion2-content [role=alert]').textContent.includes('別タブ')`))
  // Corrupt saves survive ordinary edits rather than being replaced with defaults.
  await navigate('/'); await evaluate(`localStorage.setItem('${key}','{')`); await navigate('/tools/aion2-checklist')
  await input('[data-content-id="nightmare"] input','2')
  assert.equal(await evaluate(`localStorage.getItem('${key}')`),'{')
  assert.ok(await evaluate(`!!document.querySelector('.aion2-content [role=alert]')`))
  await navigate('/'); await evaluate(`localStorage.removeItem('${key}')`)
  console.log('PASS: AION2 content persistence, shared scope, filters, restore preview, corrupt storage, eight layouts')
}
